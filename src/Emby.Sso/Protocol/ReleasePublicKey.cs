    /// <summary>
    /// The vendor's PLUGIN RELEASE signing public key, compiled into the plugin.
    ///
    /// A DIFFERENT KEY FROM THE LICENCE KEY, AND THAT IS THE WHOLE POINT. This
    /// one authorises CODE: a build signed by it will be downloaded and written
    /// into Emby's plugins directory, and then executed. The licence key
    /// authorises an assertion about a licence, which costs the vendor a sale
    /// when it is abused. These are not the same risk and must not share a key.
    ///
