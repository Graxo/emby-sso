    /// vendor chose instant self-service activation and that requires it. If
    /// that key also signed releases, anyone who broke into that service could
    /// push a backdoored DLL to every customer's media server. This key lives on
    /// the vendor's own machine, is never on a server, and is never in a CI
    /// variable - so a total compromise of the licence service still cannot ship
    /// code.
